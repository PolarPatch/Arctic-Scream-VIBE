"""The demos A1..A6 for the VIBE's K1..K6: arctic-drones' web/demos.json (made by its web/gen_demos.mjs from the
firmware's own sounds: the same demos as the FM-1's web page) as C, into firmware/arctic-scream-vibe/port/demos.h.

A demo is its actions, played one at a time as the web page plays them (web/site.js): an editor frame (SysEx, after
F0, without F7), a panic (every track's notes let go), or keys tapped (the FM-1's keys, bit 0 = F2: latched).

    tools/gen_demos.py [path to arctic-drones]      (default: ../arctic-drones)
"""
import json
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ad = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "..", "arctic-drones")
demos = json.load(open(os.path.join(ad, "web", "demos.json"), encoding="utf-8"))
if len(demos) > 6:
    sys.exit("gen_demos: K1..K6 hold six demos, demos.json has %d" % len(demos))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["/* generated by tools/gen_demos.py from arctic-drones' web/demos.json: do not edit */",
       "/* an action: DA_SX n, then n bytes (an editor frame after F0); DA_PANIC; DA_KEYS, then the mask's 4 bytes (LE) */",
       "enum { DA_END, DA_SX, DA_PANIC, DA_KEYS };"]
for i, d in enumerate(demos):
    b = []
    for a in d["act"]:
        if "sx" in a:
            sx = a["sx"]
            if len(sx) > 640:
                sys.exit("gen_demos: a frame of %d bytes (the platform takes 640)" % len(sx))
            b += [1, len(sx) & 255, len(sx) >> 8] + sx
        elif "panic" in a:
            b += [2]
        elif "keys" in a:
            m = a["keys"]
            b += [3, m & 255, m >> 8 & 255, m >> 16 & 255, m >> 24 & 255]
    b.append(0)
    rows = [", ".join(str(x) for x in b[j:j + 24]) for j in range(0, len(b), 24)]
    out.append("static const uint8_t DM_ACT%d[%d] = {\n    %s};" % (i, len(b), ",\n    ".join(rows)))
out.append("typedef struct { const char *id, *name, *sub; int tempo; const uint8_t *act; } demo_t;")
out.append("#define DM_N %du" % len(demos))
out.append("static const demo_t DEMOS[DM_N] = {")
for i, d in enumerate(demos):
    out.append("    {%s, %s, %s, %d, DM_ACT%d}," % (cstr(d["id"]), cstr(d["name"]), cstr(d["sub"]), d["tempo"], i))
out.append("};")
dst = os.path.join(root, "firmware", "arctic-scream-vibe", "port", "demos.h")
open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("gen_demos: %s" % ", ".join("%s %s" % (d["id"], d["name"]) for d in demos))
